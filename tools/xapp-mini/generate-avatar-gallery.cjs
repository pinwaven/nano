const fs = require('node:fs');
const path = require('node:path');

// Keep the miniapp manifest as the source of truth; preserve every signed URL byte for byte.
function generateAvatarGallery(gallery, moods) {
  const first = gallery[0]?.thumb;
  if (!first) throw new Error('Avatar gallery is empty');
  const imagePath = first.slice(0, first.indexOf('?'));
  const prefix = imagePath.slice(0, imagePath.lastIndexOf('/') + 1);
  const query = first.slice(first.indexOf('?') + 1, first.indexOf('Expires=') + 'Expires='.length);
  function compact(id, variant, url) {
    const head = `${prefix}${id}-${variant}.jpg?${query}`;
    if (!url.startsWith(head) || !/^\d+&Signature=.+$/.test(url.slice(head.length))) {
      throw new Error(`Unexpected URL format for ${id}/${variant}`);
    }
    return url.slice(head.length);
  }
  const rows = gallery.map(a => {
    const tails = ['thumb', 'engaged', 'relaxed', 'restored', 'stressed'].map(m =>
      compact(a.id, m, m === 'thumb' ? a.thumb : a.moods[m]));
    return `  avatar(${JSON.stringify(a.id)}, ${JSON.stringify(tails)}),`;
  });
  return `// Generated by tools/xapp-mini/generate-avatar-gallery.cjs from the miniapp manifest.
// Shared URL parts reduce bundle size; all 200 original signed URLs are reconstructed exactly.

export class AvatarEntry {
  id : string
  thumb : string
  engaged : string
  relaxed : string
  restored : string
  stressed : string

  constructor(id : string, thumb : string, engaged : string, relaxed : string, restored : string, stressed : string) {
    this.id = id
    this.thumb = thumb
    this.engaged = engaged
    this.relaxed = relaxed
    this.restored = restored
    this.stressed = stressed
  }

  moodUrl(mood : string) : string {
    if (mood == 'engaged') return this.engaged
    if (mood == 'restored') return this.restored
    if (mood == 'stressed') return this.stressed
    return this.relaxed
  }
}

const URL_PREFIX : string = ${JSON.stringify(prefix)}
const QUERY_PREFIX : string = ${JSON.stringify(query)}

function url(id : string, variant : string, signed : string) : string {
  return URL_PREFIX + id + '-' + variant + '.jpg?' + QUERY_PREFIX + signed
}

function avatar(id : string, signed : string[]) : AvatarEntry {
  return new AvatarEntry(id, url(id, 'thumb', signed[0]), url(id, 'engaged', signed[1]),
    url(id, 'relaxed', signed[2]), url(id, 'restored', signed[3]), url(id, 'stressed', signed[4]))
}

export const MOODS : string[] = ${JSON.stringify(moods)}

export const AVATAR_GALLERY : AvatarEntry[] = [
${rows.join('\n')}
]

export function findAvatar(avatarId : string | null) : AvatarEntry | null {
  if (avatarId == null) return null
  for (const a of AVATAR_GALLERY) {
    if (a.id == avatarId) return a
  }
  return null
}
`;
}

module.exports = { generateAvatarGallery };
if (require.main === module) {
  const root = path.resolve(__dirname, '../..');
  const { AVATAR_GALLERY, MOODS } = require(path.join(root, 'src/mini/nano-miniapp/utils/avatar-gallery.js'));
  const file = path.join(root, 'src/xapp/utils/avatar-gallery.uts');
  const code = generateAvatarGallery(AVATAR_GALLERY, MOODS);
  fs.writeFileSync(file, code);
  console.log(`xapp avatar gallery: ${AVATAR_GALLERY.length} characters, ${Buffer.byteLength(code)} source bytes`);
}
