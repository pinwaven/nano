const tags = { view: 'div', text: 'span', image: 'img', 'scroll-view': 'Scroll', block: 'React.Fragment', picker: 'Picker', 'user-health': 'ClientHealth', toolbox: 'CoachToolbox', input: 'input', textarea: 'textarea', button: 'button' };
function siblings(nodes) {
  let result = '';
  for (let i = 0; i < nodes.length; i++) {
    const n = nodes[i];
    if (n.attrs?.['wx:if'] !== undefined) {
      let chain = `${value(n.attrs['wx:if'])} ? (${element(n)})`;
      while (nodes[i + 1]?.attrs?.['wx:elif'] !== undefined) { const next = nodes[++i]; chain += ` : ${value(next.attrs['wx:elif'])} ? (${element(next)})`; }
      if (nodes[i + 1]?.attrs?.['wx:else'] !== undefined) chain += ` : (${element(nodes[++i])})`;
      else chain += ' : null';
      result += `{${chain}}\n`;
    } else result += n.text !== undefined ? `{${value(n.text.replace(/\s*\n\s*/g, ' ').trim())}}\n` : element(n) + '\n';
  }
  return result;
}
function element(n, loop = true) {
  const a = n.attrs;
  if (loop && a['wx:for']) {
    const item = a['wx:for-item'] || 'item', index = a['wx:for-index'] || 'index';
    return `<React.Fragment>{(${value(a['wx:for'])} || []).map((${item}, ${index}) => (${element(n, false)}))}</React.Fragment>`;
  }
  const tag = a.bindlongpress ? 'PipelineCard' : tags[n.tag]; if (!tag) throw new Error(`Unsupported coach tag ${n.tag}`);
  const attrs = [];
  if (!loop) {
    const item = a['wx:for-item'] || 'item', idx = a['wx:for-index'] || 'index';
    attrs.push(`key={${a['wx:key'] && a['wx:key'] !== 'index' ? `${item}.${a['wx:key']} ?? ${idx}` : idx}}`);
  }
  const data = Object.entries(a).filter(([k]) => k.startsWith('data-')).map(([k,v]) => `${JSON.stringify(k.slice(5).replace(/-([a-z])/g, (_, c) => c.toUpperCase()))}: ${value(v)}`).join(', ');
  const event = (name, stop = false) => `e => fire(${JSON.stringify(name)}, e, {${data}}, ${stop})`;
  const skip = /^(wx:|data-|refresher-|catchtouch|bindlongpress|bind:|bindagree|bindrefresher)/;
  for (const [k,v] of Object.entries(a)) {
    if (skip.test(k)) continue;
    if (k === 'bindtouchstart' || k === 'bindtouchend') { attrs.push(`${k === 'bindtouchstart' ? 'onTouchStart' : 'onTouchEnd'}={${event(v)}}`); continue; }
    if (k === 'bindtap' || k === 'catchtap') { attrs.push(`onClick={${event(v, k === 'catchtap')}}`); if (v !== 'noop') attrs.push(`role="button" tabIndex={0} onKeyDown={e => { if (e.target === e.currentTarget && (e.key === 'Enter' || e.key === ' ')) { e.preventDefault(); fire(${JSON.stringify(v)}, e, {${data}}, true); } }}`); continue; }
    if (k === 'bindinput' || k === 'bindchange') { attrs.push(`onChange={${event(v)}}`); continue; }
    if (k === 'style') { attrs.push(`style={style(${value(v)})}`); continue; }
    if (k === 'src') { attrs.push(`src={asset(${value(v)})}`); continue; }
    if (['confirm-type','auto-height','open-type','placeholder-class'].includes(k)) continue;
    if (k === 'mode' && n.tag !== 'picker' && n.tag !== 'user-health') continue;
    const key = { class:'className', maxlength:'maxLength', 'scroll-y':'vertical', 'scroll-x':'horizontal', 'scroll-into-view':'scrollId', 'user-id':'userId', 'coach-id':'coachId', 'text-scale':'textScale' }[k] || k;
    if (key === 'value' && a.bindchange === 'onMcGender') attrs.push('value={mcGenderIndex < 0 ? \"\" : mcGenderIndex}');
    else if (key === 'value' && a.bindchange === 'onMcDate') attrs.push('value={mcForm.birth_date || \"\"}');
    else if (key === 'value' && ['input','textarea'].includes(n.tag)) attrs.push(`value={${value(v)} ?? ''}`);
    else if (k === 'type' && (v === 'number' || v === 'digit')) attrs.push(`type="text" inputMode="${v === 'digit' ? 'decimal' : 'numeric'}"`);
    else attrs.push(`${key}={${value(v)}}`);
  }
  if (a.bindlongpress) attrs.push(`onContextMenu={e => { e.preventDefault(); fire(${JSON.stringify(a.bindlongpress)}, e, {${data}}, true); }}`);
  if (n.tag === 'user-health') attrs.push('key={detailClient.user_id}');
  if (n.tag === 'toolbox') attrs.push(`onAction={(action, file) => fire('handleChatToolAction', { detail: { action, tempFilePath: file } })}`);
  if (n.tag === 'image') attrs.push('alt=""');
  if (n.tag === 'picker' && a.bindchange === 'onGoalTypeChange') attrs.push('valueFromRange value={goalType}');
  if (n.tag === 'picker' && a.bindchange === 'onMcDate') attrs.push('max={today}');
  return `<${tag} ${attrs.join(' ')}>${siblings(n.children)}</${tag}>`.replace(/<(img|input)([^>]*?)><\/\1>/g, '<$1$2 />');
}
