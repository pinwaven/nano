// WXML uses unescaped JavaScript in attributes; an XML/HTML parser would alter its expressions.
function parse(wxml) {
  const tree = { children: [] }, stack = [tree];
  const token = /<!--[\s\S]*?-->|<\/?[\w-]+(?:\s+[\w:-]+(?:="[^"]*")?)*\s*\/?>/g;
  let cursor = 0, m;
  while ((m = token.exec(wxml))) {
    const text = wxml.slice(cursor, m.index);
    if (text.trim()) stack.at(-1).children.push({ text });
    cursor = token.lastIndex;
    if (m[0].startsWith('<!--')) continue;
    if (m[0].startsWith('</')) {
      const tag = m[0].slice(2, -1).trim();
      if (stack.pop().tag !== tag) throw new Error(`Unbalanced ${tag}`);
      continue;
    }
    const tag = /^<([\w-]+)/.exec(m[0])[1];
    const attrs = {};
    for (const a of m[0].slice(tag.length + 1).matchAll(/([\w:-]+)(?:="([^"]*)")?/g)) attrs[a[1]] = a[2] ?? true;
    const node = { tag, attrs, children: [] };
    stack.at(-1).children.push(node);
    if (!m[0].endsWith('/>')) stack.push(node);
  }
  if (stack.length !== 1) throw new Error('Unclosed WXML');
  return tree.children;
}
function value(v) {
  if (v === true) return 'true';
  const parts = [], re = /{{([\s\S]*?)}}/g; let end = 0, m;
  while ((m = re.exec(v))) {
    if (m.index > end) parts.push(JSON.stringify(v.slice(end, m.index)));
    parts.push(`(${m[1].trim()})`); end = re.lastIndex;
  }
  if (end < v.length) parts.push(JSON.stringify(v.slice(end)));
  return parts.join(' + ') || '""';
}
