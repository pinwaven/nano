function labelInputs(nodes) {
  for (const node of nodes) {
    if (!node.children) continue;
    const label = node.children.find(n => n.tag === 'text' && /form-label/.test(n.attrs.class || ''));
    if (label) for (const input of node.children.filter(n => n.tag === 'input' || n.tag === 'textarea')) input.attrs['aria-label'] = label.children.map(n => n.text || '').join('').trim();
    labelInputs(node.children);
  }
}
